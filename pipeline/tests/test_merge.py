def test_suspect_crops_needs_both_a_missing_border_and_a_narrow_box():
    """Census over all 469 crops: a missing border alone flags 6 (5 of them just sit on a dark
    background), a narrow box alone flags 10 (9 are genuinely short tooltips). Together: 1."""
    geometry = {
        "cut": (181, 0.16),          # piercing-ice: narrow AND no right border
        "dark-background": (219, 0.16),
        "short-tooltip": (175, 0.72),
        **{f"normal-{i}": (221, 0.65) for i in range(6)},
    }
    assert MR.suspect_crops(geometry) == {"cut"}


def test_suspect_crops_needs_a_population_to_compare_against():
    assert MR.suspect_crops({"a": (181, 0.16), "b": (221, 0.65)}) == set()


def test_crop_geometry_reads_a_real_crop(tmp_path):
    import cv2
    import numpy as np
    img = np.zeros((60, 100, 3), np.uint8)
    img[:] = 10
    img[:3, :] = img[-3:, :] = img[:, :3] = img[:, -3:] = 200      # a complete border
    p = tmp_path / "whole.png"
    cv2.imwrite(str(p), img)
    w, ratio = MR.crop_geometry(p)
    assert w == 100 and ratio > 0.9
    img[:, -3:] = 10                                               # right border cut away
    p2 = tmp_path / "cut.png"
    cv2.imwrite(str(p2), img)
    assert MR.crop_geometry(p2)[1] < 0.2
    assert MR.crop_geometry(tmp_path / "missing.png") is None


def test_a_settled_record_leaves_the_queue_even_after_a_stale_run_flagged_it():
    """Confidence and note are recomputed from the evidence, never nudged, so a warning a
    previous run wrote (say, a crop rule that has since been tightened) does not linger."""
    text = "Reduces the mana cost of your Shock spells by 2%."
    rec = _rec(text, [("qwen/3x", text), ("codex-cli", text)], conf=0.7)
    rec["source"]["note"] = "points already spent; crop is 181 px wide and missing a tooltip border"
    MR.apply_merge(rec, set(), at="t")
    assert rec["source"]["confidence"] == 1.0
    assert rec["source"]["note"] == "points already spent"


def test_settle_puts_a_cut_off_crop_back_in_the_queue():
    text = "Increases the damage done by yo"
    rec = _rec(text, [("qwen/3x", text), ("codex-cli", text)], conf=1.0)
    MR.apply_merge(rec, set(), at="t")
    assert rec["source"]["confidence"] == 1.0
    MR.settle(rec, "crop is 181 px wide and missing a tooltip border, so the tooltip is cut off")
    assert rec["source"]["confidence"] == 0.7
    assert "181 px wide" in rec["source"]["note"]
    MR.settle(rec)                                   # re-cropped: the warning goes away again
    assert rec["source"]["confidence"] == 1.0 and "note" not in rec["source"]


def test_a_footer_only_difference_is_not_a_doubt():
    """Stage 5 lists `footer` in differs_in while keeping full confidence: the green
    "Click to learn" line is not talent data and must not fill the review queue."""
    rec = {"source": {"agreement": {"confidence": 1.0, "differs_in": ["footer"]}}}
    assert MR.unadjudicated_doubts(rec) == []
    rec2 = {"source": {"agreement": {"confidence": 0.7, "differs_in": ["footer", "extra_lines"]}}}
    assert MR.unadjudicated_doubts(rec2) == ["extra_lines"]
