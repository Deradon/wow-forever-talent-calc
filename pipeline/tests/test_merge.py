# --------------------------------------------------------------------------- merge

def test_second_reader_wins_on_case():
    """audit 3.1: 27 records read `Increases`/`Instant` mid-sentence; the glyph is x-height."""
    res = M.merge_readings("... and Increases all threat generated by 30%.",
                           "... and increases all threat generated by 30%.")
    assert res.text.endswith("and increases all threat generated by 30%.")
    assert res.counts() == {M.CASE: 1}


def test_second_reader_wins_on_comma_read_as_period():
    """audit 3.2: druid/ferocity reads the same glyph as ',' after Maul and '.' after Mangle."""
    res = M.merge_readings("Reduces the cost of your Maul, Mangle. Swipe. Claw, and Rake abilities by 10 Rage.",
                           "Reduces the cost of your Maul, Mangle, Swipe, Claw, and Rake abilities by 10 Rage.")
    assert res.text == "Reduces the cost of your Maul, Mangle, Swipe, Claw, and Rake abilities by 10 Rage."
    assert res.counts() == {M.PUNCT: 2}


def test_second_reader_wins_on_a_dropped_percent():
    """audit 3.3: the most damaging shape - a percentage silently becomes a flat number
    that the rank scaler then multiplies (mage/shatter produced 150 % crit)."""
    res = M.merge_readings("Increases the critical strike chance against frozen targets by 50.",
                           "Increases the critical strike chance against frozen targets by 50%.")
    assert res.text.endswith("by 50%.")
    assert res.counts() == {M.PERCENT: 1}


def test_wording_goes_to_the_majority_not_to_the_second_reader():
    """audit 3.4: mage/pyroblast - the 2x Qwen pass and codex both read 'Hurls'."""
    res = M.merge_readings("Hurts an immense fiery boulder that inflicts damage.",
                           "Hurls an immense fiery boulder that inflicts damage.",
                           ["Hurls an immense fiery boulder that inflicts damage."])
    assert res.text.startswith("Hurls")
    assert res.counts() == {M.WORD: 1}


def test_wording_stays_with_the_primary_when_the_second_reader_is_alone():
    """audit 2: in 21 of the 77 queue records the second reader was the one that was wrong
    (druid/furor 'regain', not codex's 'retain')."""
    res = M.merge_readings("you regain 10 rage", "you retain 10 rage", ["you regain 10 rage"])
    assert res.text == "you regain 10 rage"
    assert res.counts() == {}


def test_an_unbacked_word_disagreement_is_reported_as_disputed():
    res = M.merge_readings("you regain 10 rage", "you retain 10 rage")
    assert res.text == "you regain 10 rage"          # tie: the primary reader keeps it
    assert [h.primary for h in res.disputed_words] == ["regain"]


def test_inserted_and_deleted_runs_are_voted_on_as_wording():
    """priest/devouring-contagion: a spurious 'it' the primary reader invented."""
    res = M.merge_readings("while Devouring Plague it is active", "while Devouring Plague is active",
                           ["while Devouring Plague is active"])
    assert res.text == "while Devouring Plague is active"
    assert res.counts() == {M.WORD: 1}


def test_case_punct_and_percent_in_one_description():
    res = M.merge_readings("Deals damage to Lightning Bolt. Chain Lightning and Increases it by 5.",
                           "Deals damage to Lightning Bolt, Chain Lightning and increases it by 5%.")
    assert res.text == "Deals damage to Lightning Bolt, Chain Lightning and increases it by 5%."
    assert res.counts() == {M.PUNCT: 1, M.CASE: 1, M.PERCENT: 1}


def test_identical_readings_change_nothing():
    text = "Increases the damage done by your Entangling Roots spell by 5%."
    res = M.merge_readings(text, text)
    assert res.text == text and not res.changed and res.counts() == {}


def test_an_empty_or_missing_second_reading_leaves_the_primary_alone():
    assert M.merge_readings("primary text", "").text == "primary text"
    assert M.merge_readings("", "secondary text").text == "secondary text"


def test_merge_never_invents_words_outside_the_two_readings():
    a, b = "alpha beta gamma delta", "alpha BETA gamma epsilon zeta"
    res = M.merge_readings(a, b)
    for word in res.text.split():
        assert word in a.split() or word in b.split()


