# --------------------------------------------------------------------------- record level

def _rec(desc: str, readings: list[tuple[str, str]], conf: float = 0.7, cls: str = "shaman") -> dict:
    return {"id": f"{cls}/t/r0c0", "class": cls, "name": "Concussion", "rank": {"current": 0, "max": 5},
            "description_rank1": desc, "ranks_anticipated": {"description": "stale", "ranksSource": "observed"},
            "source": {"confidence": conf, "reader": "qwen",
                       "note": "second reader (codex) differs in description",
                       "readings": [{"reader": r, "name": "Concussion", "description": d, "maxRank": 5,
                                     "confidence": 1.0} for r, d in readings]}}


def test_apply_merge_rewrites_the_record_and_clears_the_queue_flag():
    rec = _rec("Increases the damage of Lightning Bolt. Chain Lightning by 5.",
               [("qwen/3x", "Increases the damage of Lightning Bolt. Chain Lightning by 5."),
                ("qwen/2x", "Increases the damage of Lightning Bolt. Chain Lightning by 5."),
                ("codex-cli", "Increases the damage of Lightning Bolt, Chain Lightning by 5%.")])
    rep = MR.apply_merge(rec, set(), at="2026-09-13T00:00:00Z")
    assert rec["description_rank1"] == "Increases the damage of Lightning Bolt, Chain Lightning by 5%."
    assert rep["shapes"] == {M.PUNCT: 1, M.PERCENT: 1}
    assert rec["source"]["confidence"] == 1.0        # the disagreement is settled: out of the queue
    assert "note" not in rec["source"]               # the stale "second reader differs" clause is gone
    assert "ranks_anticipated" not in rec            # stage 6/8 re-derives the template and the ranks
    pre = [r for r in rec["source"]["readings"] if r["reader"] == "pre-merge"]
    assert len(pre) == 1 and pre[0]["description"].endswith("by 5.")   # provenance kept


def test_apply_merge_keeps_a_disputed_record_in_the_queue():
    rec = _rec("you regain 10 rage", [("qwen/3x", "you regain 10 rage"), ("codex-cli", "you retain 10 rage")])
    rep = MR.apply_merge(rec, set(), at="t")
    assert rec["description_rank1"] == "you regain 10 rage"
    assert rec["source"]["confidence"] == 0.7
    assert "readers still differ on 'regain' vs 'retain'" in rec["source"]["note"]
    assert rep["changed"] is False
    assert "ranks_anticipated" in rec                # nothing changed, so nothing to recompute


def test_apply_merge_is_idempotent():
    rec = _rec("Lightning Bolt. Chain Lightning",
               [("qwen/3x", "Lightning Bolt. Chain Lightning"), ("codex-cli", "Lightning Bolt, Chain Lightning")])
    MR.apply_merge(rec, set(), at="t")
    first = json.dumps(rec, sort_keys=True)
    MR.apply_merge(rec, set(), at="t")
    assert json.dumps(rec, sort_keys=True) == first


def test_apply_merge_leaves_a_clean_records_text_alone_and_clears_its_stale_note():
    text = "Reduces the mana cost of your Shock spells by 2%."
    rec = _rec(text, [("qwen/3x", text), ("codex-cli", text)], conf=1.0)
    assert MR.apply_merge(rec, set(), at="t") is None
    assert rec["description_rank1"] == text and rec["name"] == "Concussion"
    assert rec["source"]["confidence"] == 1.0
    assert "note" not in rec["source"]          # the superseded "second reader differs" clause is gone
    assert "ranks_anticipated" in rec


def test_spell_name_repair_only_runs_inside_the_review_queue(prior_doc):
    """Census over all 469 records: the dictionary is right 6/6 inside the queue and wrong
    8/8 outside it, and every text error the audit found sits inside the queue."""
    vocab = MR.class_vocabulary(prior_doc, "warlock")
    text = "damage if the target is afflicted by Immolates."
    queued = _rec(text, [("qwen/3x", text), ("codex-cli", text)], conf=0.7, cls="warlock")
    MR.apply_merge(queued, vocab, at="t")
    assert queued["description_rank1"].endswith("Immolate.")
    trusted = _rec(text, [("qwen/3x", text), ("codex-cli", text)], conf=1.0, cls="warlock")
    assert MR.apply_merge(trusted, vocab, at="t") is None
    assert trusted["description_rank1"].endswith("Immolates.")


def test_note_handling_keeps_unrelated_clauses():
    assert MR.strip_merge_clauses("points already spent; second reader (codex) differs in description") == \
        "points already spent"
    assert MR.strip_merge_clauses(None) == ""
    src = {"note": "points already spent; readers still differ on 'x' vs 'y'"}
    MR.set_note(src, "readers still differ on 'a' vs 'b'")
    assert src["note"] == "points already spent; readers still differ on 'a' vs 'b'"


def test_set_note_is_idempotent_and_drops_a_settled_clause():
    src = {"note": "points already spent"}
    for _ in range(3):
        MR.set_note(src, "readers still differ on 'a' vs 'b'", "crop is 181 px wide and missing a tooltip border")
    assert src["note"] == ("points already spent; readers still differ on 'a' vs 'b'; "
                           "crop is 181 px wide and missing a tooltip border")
    # an older run's wording of the same clauses is stripped too, not stacked on top
    stale = {"note": "points already spent; footer (not adjudicated by the merge); "
                     "it is probably cut off and the reading cannot be verified; re-crop the cell"}
    MR.set_note(stale)
    assert stale["note"] == "points already spent"
    MR.set_note(src)                       # nothing open any more
    assert src["note"] == "points already spent"
    MR.set_note({"note": "readers still differ on 'a' vs 'b'"})
    src2 = {"note": "readers still differ on 'a' vs 'b'"}
    MR.set_note(src2)
    assert "note" not in src2              # an empty note is removed, not left as ""


